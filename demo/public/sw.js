const CACHE_NAME = 'voicegis-v5';
const APP_SHELL = ['./', './index.html', './manifest.webmanifest'];
// Application code is same-origin now that Leaflet is bundled; the only
// third-party requests left are basemap tiles.
const CACHEABLE_HOSTS = [
  'basemaps.cartocdn.com',
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(APP_SHELL))
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(
      keys
        .filter((key) => key.startsWith('voicegis-') && key !== CACHE_NAME)
        .map((key) => caches.delete(key))
    ))
  );
  self.clients.claim();
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  const sameOrigin = url.origin === self.location.origin;
  const cacheableExternal = CACHEABLE_HOSTS.some((host) => url.hostname.endsWith(host));
  const isNavigation = request.mode === 'navigate';

  if (!sameOrigin && !cacheableExternal) return;
  if (url.hostname.includes('nominatim') || url.hostname.includes('gibs.earthdata.nasa.gov')) return;

  if (isNavigation) {
    event.respondWith(
      fetch(request)
        .then((response) => {
          const copy = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put('./index.html', copy));
          return response;
        })
        .catch(() => caches.match('./index.html'))
    );
    return;
  }

  event.respondWith(
    caches.match(request).then((cached) => {
      const network = fetch(request)
        .then((response) => {
          if (response.ok || response.type === 'opaque') {
            const copy = response.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
          }
          return response;
        })
        .catch(() => cached);
      return cached || network;
    })
  );
});
